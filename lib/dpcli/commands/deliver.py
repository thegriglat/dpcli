def gen_line():
    return "<!-- " + lang_text("generated by dpcli deliver; do not edit by hand", "generated by dpcli deliver; не править руками") + " -->"


WHO = {"user": ("user", "пользователь"), "coordinator": ("coordinator", "координатор"),
       "main": ("main session", "главная сессия"), "executor": ("executor", "исполнитель")}


def who(k, default=None):
    return lang_text(*WHO[k]) if k in WHO else default


def keep_files():
    return list(config.get("deliver.keep") or ["decisions.md", "summary.md"])


def archive_tag(mod):
    t = config.get("deliver.archive_tag", "archive/{module}")
    return config.subst(t, module=mod) if t else None


def resolve_generated(root, files):
    from .docs import resolve_generated as rg
    return rg(root, files)


def fm(mod, summary, area=None, archive=None, plan=True):
    from .docs import dump_fm  # same frontmatter format that docs check validates
    d = {"type": "journal", "status": "closed", "module": mod}
    if area:
        d["area"] = area
    # a module may have no plan file: no dangling link for docs check
    d.update({"updated": now()[:10], "summary": summary, "related": [f"{config.plan_dir()}/{mod}.md"] if plan else []})
    if archive:
        d["archive"] = archive
    d["generated"] = True
    return dump_fm(d) + gen_line() + "\n"


def task_order(cards, st):
    """Task IDs in natural order: PP-2 before PP-10."""
    ids = list(dict.fromkeys(list(cards) + list(st)))
    return sorted(ids, key=lambda t: [int(x) if x.isdigit() else x for x in re.split(r"(\d+)", t)])


def day(t):
    """Journal entry date YYYY-MM-DD: nobody needs the time half a year later."""
    return t[:10] if t and len(t) >= 10 else ""


def approved():
    return lang_text("approved by the developer", "утверждено разработчиком")


def __getattr__(name):  # APPROVED depends on the configured language: resolve lazily
    if name == "APPROVED":
        return approved()
    raise AttributeError(name)


# a "why" that only names the source ("user's answer 2026-10-09") is not a reason; Russian forms kept for old journals
SOURCE_ONLY = re.compile(r"(?:(?:уточнени[ея]|указани[ея]|ответы?|постановка|сообщени[ея]|требовани[ея]|разрешение|правило"
                         r"|исправление|решени[ея]|приёмка)(?: на вопрос)?(?: пользователя)?|пользователь"
                         r"|(?:clarifications?|instructions?|answers?|statement|messages?|requirements?|permission|rule"
                         r"|fix|decisions?|acceptance)(?: to (?:the )?question)?(?: (?:from|of) (?:the )?user)?|user)"
                         r"(?: \d{4}-\d{2}-\d{2})?", re.I)


def why_of(d):
    """Reason of a decision for humans: a user decision with no reason (or only a source reference) gets
    "approved by the developer"; otherwise as recorded."""
    w = one(d.get("why") or "")
    if d.get("by") == "user" and (not w or SOURCE_ONLY.fullmatch(w)):
        return approved()
    return w


def one(s):
    return " ".join(str(s).split())


def item(x):
    """Report item: string or object (uncertain: where/why/checked) -> one line."""
    if isinstance(x, dict):
        parts = [f"`{x['where']}`" if x.get("where") else ""] + [one(x[k]) for k in ("why", "what", "text") if x.get(k)]
        if x.get("checked"):
            parts.append(f"{lang_text('checked', 'проверено')}: {one(x['checked'])}")
        rest = {k: v for k, v in x.items() if k not in ("where", "why", "what", "text", "checked")}
        if rest:
            parts.append(one(json.dumps(rest, ensure_ascii=False)))
        return " — ".join(p for p in parts if p)
    return one(x)


def render_decisions(mod, home, area=None, archive=None, plan=True):
    """Questions with answers and decisions, for humans; an answer sits under its question, not among decisions."""
    decs = read_jsonl(home / "decisions.jsonl")
    answers = {}
    for d in decs:
        if d.get("answers"):
            answers.setdefault(d["answers"], []).append(d)
    qs = [d for d in decs if d.get("kind") == "question"]
    plain = [d for d in decs if d.get("kind") != "question" and not d.get("answers")]
    T = lang_text
    L = [T(f"# {mod} — decisions and questions", f"# {mod} — решения и вопросы"), "",
         T(f"Plan: `{config.plan_dir()}/{mod}.md`. Decisions: who chose an option and why; questions: forks "
           f"where work stopped until answered.",
           f"План — `{config.plan_dir()}/{mod}.md`. Решения — кто и почему выбрал вариант; вопросы — развилки, "
           f"на которых работа останавливалась до ответа.")
         + (T(f" Full journal (cards, reports, events) is in git: `{archive}`.",
              f" Полный журнал (карточки, отчёты, события) — в git: `{archive}`.") if archive else ""), ""]
    L += [T("## Questions and answers", "## Вопросы и ответы"), ""]
    for q in qs:
        L.append(f"### {q.get('id', '?')} — {day(q.get('t', ''))}, {T('asked by', 'спросил')} {who(q.get('by'), q.get('by', '-'))}")
        L += ["", one(q.get("text", "")), ""]
        if q.get("why"):
            L += [f"{T('Context', 'Контекст')}: {one(q['why'])}", ""]
        for a in answers.get(q.get("id"), []):
            L.append(f"**{T('Answer', 'Ответ')}** ({who(a.get('by'), a.get('by', '-'))}, {day(a.get('t', ''))}): {one(a.get('text', ''))}"
                     + (f" {T('Why', 'Почему')}: {one(a['why'])}" if a.get("why") and not SOURCE_ONLY.fullmatch(one(a["why"])) else ""))
            L.append("")
        if not answers.get(q.get("id")):
            L += [T("**No answer.**", "**Ответа нет.**"), ""]
    if not qs:
        L += [T("No questions.", "Вопросов не было."), ""]
    L += [T("## Decisions", "## Решения"), ""]
    for by in ("user", "main", "coordinator", "executor"):
        rows = [d for d in plain if d.get("by") == by]
        if not rows:
            continue
        L += [f"### {T('Decisions', 'Решения')}: {who(by)}", ""]
        for d in rows:
            w = why_of(d)
            L.append(f"- {day(d.get('t', ''))} — {one(d.get('text', ''))}" + (f" *{T('Why', 'Почему')}:* {w}" if w else ""))
        L.append("")
    other = [d for d in plain if d.get("by") not in WHO]
    for d in other:
        w = why_of(d)
        L.append(f"- {day(d.get('t', ''))} ({d.get('by', '-')}) — {one(d.get('text', ''))}" + (f" *{T('Why', 'Почему')}:* {w}" if w else ""))
    if not plain:
        L.append(T("No decisions recorded.", "Решений не записано."))
    n_ans = sum(1 for q in qs if answers.get(q.get("id")))
    summ = T(f"Decisions ({len(plain)}) and questions ({len(qs)}, {n_ans} answered) of module {mod}",
             f"Решения ({len(plain)}) и вопросы ({len(qs)}, отвечено {n_ans}) модуля {mod}")
    return fm(mod, summ, area, archive, plan) + "\n" + "\n".join(L).rstrip() + "\n"


def render_summary(mod, home, area=None, archive=None, plan=True):
    """Implementation summary: task, outcome, what is not done, what the executor is unsure about, its questions, review verdict."""
    cards = task_cards(home)
    st = task_states(home)
    tasks = home / "tasks"
    T = lang_text
    L = [T(f"# {mod} — implementation summary", f"# {mod} — сводка реализации"), "",
         T(f"Per module task: executor's outcome, what is not done, where it is unsure. Plan: `{config.plan_dir()}/{mod}.md`, "
           f"decisions: `decisions.md`.",
           f"По задачам модуля: итог исполнителя, что не сделано, где он не уверен. План — `{config.plan_dir()}/{mod}.md`, "
           f"решения — `decisions.md`."), "", T("## Tasks", "## Задачи"), ""]
    open_ = []
    order = task_order(cards, st)
    for tid in order:
        c = cards.get(tid) or {}
        s = st.get(tid, {"status": "created"})
        status = T("merged", "влита") if "merged" in s.get("seen", set()) else s["status"]
        if s["status"] not in FINAL:
            open_.append(tid)
        r = read_json(tasks / f"{tid}.report.json") or {}
        rv = read_json(tasks / f"{tid}.review.json") or {}
        L += [f"### {tid} — {one(c.get('title', ''))}", ""]
        meta = f"{T('Status', 'Статус')}: **{status}**"
        if rv.get("verdict"):
            meta += f"; {T('review', 'ревью')}: {rv['verdict']}"
        L += [meta, ""]
        if r.get("summary"):
            L += [one(r["summary"]), ""]
        elif s.get("note"):
            L += [one(s["note"]), ""]
        for key, title in (("not_done", T("Not done", "Не сделано")), ("uncertain", T("Unsure", "Не уверен")),
                           ("questions", T("Executor questions", "Вопросы исполнителя"))):
            vals = [v for v in r.get(key) or [] if v]
            if vals:
                L.append(f"{title}:")
                L += [f"- {item(v)}" for v in vals]
                L.append("")
    if not order:
        L += [T("No tasks.", "Задач нет."), ""]
    summ = T(f"Implementation summary of module {mod}: {len(order)} tasks, executor outcomes and caveats",
             f"Сводка реализации модуля {mod}: {len(order)} задач, итоги и оговорки исполнителей")
    return fm(mod, summ, area, archive, plan) + "\n" + "\n".join(L).rstrip() + "\n", open_


def write_md(mod, home, dest, root, area=None, archive=None):
    """decisions.md and summary.md from journal home into directory dest of copy root. -> (paths, open tasks)."""
    dest.mkdir(parents=True, exist_ok=True)
    plan = (Path(root) / config.plan_dir() / f"{mod}.md").is_file()  # in the copy the md is written for
    summary, open_ = render_summary(mod, home, area, archive, plan)
    files = {"decisions.md": render_decisions(mod, home, area, archive, plan), "summary.md": summary}
    out = []
    for name in keep_files():
        if name in files:
            (dest / name).write_text(files[name], encoding="utf-8")
            out.append(dest / name)
    return out, open_


def drop_journal(cwd, rel_dir, keep):
    """Remove from index and disk everything in rel_dir except keep (file names at the root of rel_dir)."""
    d = Path(cwd) / rel_dir
    tracked = [f for f in gitx.gitr("-c", "core.quotepath=off", "ls-files", "-z", "--", rel_dir, cwd=cwd).stdout.split("\0") if f]
    gone = [f for f in tracked if f not in {f"{rel_dir}/{k}" for k in keep}]
    if gone:
        r = gitx.gitr("rm", "-q", "-f", "--", *gone, cwd=cwd)
        if r.returncode:
            raise DpError(f"git rm: {gitx.gerr(r)}")
    if d.is_dir():
        for p in d.iterdir():
            if p.name not in keep:
                shutil.rmtree(p) if p.is_dir() else p.unlink()
    return gone


FM_LINE = re.compile(r"^(\w+):")


def set_fm(text, **vals):
    """Change/add frontmatter keys line by line, leaving the rest of the format intact (YAML lists, quotes)."""
    if not text.startswith("---\n") or text.find("\n---", 4) < 0:
        return None
    end = text.find("\n---", 4)
    lines = text[4:end].split("\n")
    quoted = any(re.match(r'^\w+: "', l) for l in lines)  # file style: JSON strings or bare YAML
    for k, v in vals.items():
        val = json.dumps(v, ensure_ascii=False) if quoted or not re.fullmatch(r"[\w.-]+", str(v)) else str(v)
        idx = next((i for i, l in enumerate(lines) if (m := FM_LINE.match(l)) and m[1] == k), None)
        if idx is not None:
            lines[idx] = f"{k}: {val}"
            continue
        after = {"area": "module"}.get(k)
        pos = next((i + 1 for i, l in enumerate(lines) if (m := FM_LINE.match(l)) and m[1] == after), len(lines))
        lines.insert(pos, f"{k}: {val}")
    return "---\n" + "\n".join(lines) + text[end:]


def close_docs(root, mod, area, day=None):
    """Module plan and its contracts (module in frontmatter) -> status: closed, updated (day or today), area. -> paths from root."""
    from .docs import split_fm
    root = Path(root)
    cands = [root / config.plan_dir() / f"{mod}.md"]
    cdir = root / config.contracts_dir()
    if cdir.is_dir():
        for p in sorted(cdir.glob("*.md")):
            if p not in cands and (split_fm(p.read_text(encoding="utf-8"))[0] or {}).get("module") == mod:
                cands.append(p)
    out = []
    for p in cands:
        if not p.exists():
            continue
        text = p.read_text(encoding="utf-8")
        f = split_fm(text)[0]
        if f is None:
            continue
        vals = {"status": "closed"}
        if area and f.get("area") != area:
            vals["area"] = area
        if f.get("status") == "closed" and "area" not in vals:
            continue
        vals["updated"] = day or now()[:10]
        p.write_text(set_fm(text, **vals), encoding="utf-8")
        out.append(p.relative_to(root).as_posix())
    return out


def reindex(root):
    """docs index in copy root -> changed paths from root (INDEX.md, registries); no docs directory: []."""
    from .docs import Ctx, cmd_index
    x = Ctx(root)
    if not x.docs.is_dir():
        return []
    cmd_index(x, None)
    return [x.index_path, x.reg]


def finish(root, mod, area):
    """After delivery: close plan and contracts, rebuild the index, stage everything."""
    paths = close_docs(root, mod, area) + reindex(root)
    if paths:
        gitx.gitr("add", "--", *paths, cwd=root)
    return paths


def journal_from(ref, rel_dir, dest):
    """Journal directory rel_dir from commit/tag ref -> dest/rel_dir (git archive, no checkout)."""
    r = subprocess.run(["git", "archive", "--format=tar", ref, "--", rel_dir], cwd=gitx.toplevel(), capture_output=True)
    if r.returncode:
        raise DpError(f"no journal {rel_dir} in {ref}: {r.stderr.decode(errors='replace').strip()}")
    shutil.rmtree(dest, ignore_errors=True)
    with tarfile.open(fileobj=io.BytesIO(r.stdout)) as t:
        try:
            t.extractall(dest, filter="data")
        except TypeError:  # Python < 3.12: no filter; the archive is our own journal from git
            t.extractall(dest)
    return dest / rel_dir


def cmd_rerender(a, rel_dir):
    """md of a delivered module anew from the archived journal: when the format changes, "do not edit by hand" files are not edited by hand."""
    ref = a.from_ or archive_tag(a.module)
    if not ref:
        raise DpError("--from required: a tag or commit with the module journal (deliver.archive_tag is not set)")
    top = gitx.toplevel()
    tmp = top / "build" / "dpcli" / f"rerender-{a.module}"
    home = journal_from(ref, rel_dir, tmp)
    if not (home / "events.jsonl").exists() and not (home / "module.json").exists():
        raise DpError(f"no dpcli journal in {ref}:{rel_dir}")
    area = a.area or module_meta(a.module, home).get("area")
    check_area(area)
    if a.dry:
        print(f"{a.module}: {', '.join(keep_files())} from {ref}, area {area or '-'}; plan and contracts -> closed")
        shutil.rmtree(tmp, ignore_errors=True)
        return
    # journal link in md only if archive tags are enabled: otherwise ref exists only in this copy
    made, _ = write_md(a.module, home, top / rel_dir, top, area, ref if archive_tag(a.module) else None)
    last = max((str(e.get("t", "")) for e in read_jsonl(home / "events.jsonl")), default="")[:10] or None
    shutil.rmtree(tmp, ignore_errors=True)
    closed = close_docs(top, a.module, area, last)  # closing date is the last journal entry, not the rebuild day
    reindex(top)
    print(f"{a.module}: {', '.join(p.name for p in made)} from {ref}" + (f"; closed {', '.join(closed)}" if closed else "")
          + "; INDEX.md rebuilt; not committed")


def commit(cwd, msg, body):
    args = ["commit", "-q", "-m", msg] + (["-m", body] if body else []) + (["-m", session_line()] if session_line() else [])
    r = subprocess.run(["git", *args], cwd=cwd, text=True)  # hooks (pre-commit) print to the terminal
    if r.returncode:
        raise DpError(f"git commit failed (code {r.returncode}); changes left staged in {pretty(cwd)} — "
                      f"fix and commit by hand or roll back with `git reset --merge`")
    return gitx.gitr("rev-parse", "--short", "HEAD", cwd=cwd).stdout.strip()


def body_text(mod, home):
    st = task_states(home)
    cards = task_cards(home)
    lines = []
    for tid in task_order(cards, st):
        if st.get(tid, {}).get("status") == "cancelled":
            continue
        lines.append(f"- {tid}: {one((cards.get(tid) or {}).get('title', ''))}")
    return "\n".join(lines)


def plan_title(mod):
    p = gitx.toplevel() / config.plan_dir() / f"{mod}.md"
    if p.exists():
        for line in p.read_text(encoding="utf-8").splitlines():
            if line.startswith("# "):
                return line[2:].strip()
    return mod


def cmd_deliver(a):
    pd = config.plan_dir()
    rel_dir = f"{pd}/{a.module}"
    keep = keep_files()
    by = by_default(a)
    if a.rerender:
        return cmd_rerender(a, rel_dir)
    if a.in_place:
        top = gitx.toplevel()
        home = top / rel_dir
        if not (home / "events.jsonl").exists() and not (home / "module.json").exists():
            raise DpError(f"no dpcli journal in {rel_dir}")
        if gitx.dirty(top):
            raise DpError(f"copy {pretty(top)} is dirty — commit or discard changes first")
        if a.dry:
            print(f"{rel_dir}: will keep {', '.join(keep)}; will delete {len(gitx.git('ls-files', '--', rel_dir).splitlines())} journal files")
            return
        tmp = top / "build" / "dpcli" / f"deliver-{a.module}"
        area = module_meta(a.module, home).get("area")
        check_area(area)
        archive = gitx.gitr("rev-parse", "--short", "HEAD", cwd=top).stdout.strip()  # last commit with the journal
        made, _ = write_md(a.module, home, tmp, top, area, archive if archive_tag(a.module) else None)
        keep_items(a.module)
        drop_journal(top, rel_dir, keep)
        home.mkdir(parents=True, exist_ok=True)
        for p in made:
            shutil.move(str(p), home / p.name)
        shutil.rmtree(tmp, ignore_errors=True)
        gitx.gitr("add", "--", *[f"{rel_dir}/{p.name}" for p in made], cwd=top)
        finish(top, a.module, area)
        h = commit(top, lang_commit(f"{a.module}: dpcli journal folded into {', '.join(p.name for p in made)}",
                           f"{a.module}: журнал dpcli свёрнут в {', '.join(p.name for p in made)}"), "")
        print(f"{a.module}: {h}, kept in {rel_dir}: {', '.join(p.name for p in made)}")
        return

    mods = all_modules()
    if a.module not in mods:
        raise DpError(f"module {a.module} not found")
    home = mods[a.module]
    meta = module_meta(a.module, home)
    br = meta["branch"]
    check_area(meta.get("area"))
    into = a.into or module_base(meta)
    guard_main(into, bool(a.into), meta.get("base"))
    if br == into:
        raise DpError(f"module branch {br} is the same as the target")
    target = gitx.copy_of(into)
    if not target:
        raise DpError(f"branch {into} is not checked out anywhere — a copy with it open is required")
    st = task_states(home)
    open_ = [t for t in list(task_cards(home)) if st.get(t, {}).get("status") not in FINAL]
    from ..journal import open_questions
    oq = [q.get("id") for q in open_questions(home)]
    if (open_ or oq) and not a.force:
        raise DpError("module not closed: " + "; ".join(x for x in (
            f"tasks not accepted: {', '.join(open_)}" if open_ else "", f"unanswered questions: {', '.join(oq)}" if oq else "") if x)
            + " (--force to deliver as is)")
    mcopy = gitx.copy_of(br)
    tag = archive_tag(a.module)
    if a.dry:
        print(f"{br} → {into} ({pretty(target)}): squash, {rel_dir} keeps {', '.join(keep)}"
              + (f"; tag {tag}" if tag else ""))
        return
    if mcopy:
        jm = journal_commit(mcopy)
        if jm:
            print(f"dpcli journal committed in {pretty(mcopy)}")
        if gitx.dirty(mcopy):
            raise DpError(f"module copy {pretty(mcopy)} is dirty — uncommitted changes will not be delivered")
    if gitx.dirty(target):
        raise DpError(f"copy {pretty(target)} is dirty — refusing")
    keep_items(a.module)  # before the squash touches the target: a failure here leaves nothing half-done
    r = gitx.gitr("merge", "--squash", br, cwd=target)
    files = [f for f in gitx.gitr("-c", "core.quotepath=off", "diff", "--name-only", "-z", "--diff-filter=U",
                                  cwd=target).stdout.split("\0") if f] if r.returncode else []
    if r.returncode and not (files and resolve_generated(target, files)):  # finish rebuilds the indexes anyway
        gitx.gitr("reset", "--merge", cwd=target)
        raise DpError(f"squash conflict {br} into {into}, aborted; files: {', '.join(files) or gitx.gerr(r)}"
                      f" — run `{CLI} sync {a.module}` first")
    drop_journal(target, rel_dir, keep)
    made, _ = write_md(a.module, home, target / rel_dir, target, meta.get("area"), tag)
    gitx.gitr("add", "--", *[str(p) for p in made], cwd=target)
    finish(target, a.module, meta.get("area"))
    if not gitx.gitr("diff", "--cached", "--quiet", cwd=target).returncode:
        print(f"{into}: no changes — {br} already delivered")
        return
    title = a.message or f"{a.module}: {plan_title(a.module)}"
    h = commit(target, title if len(title) <= 72 else title[:71] + "…", body_text(a.module, home))
    add_event(home, None, "delivered", by, note=f"squash into {into}: {h}", commits=[h])
    if mcopy:
        journal_commit(mcopy)
    out = f"{into} {h}: squash {br}, journal -> {', '.join(p.name for p in made)}"
    if tag:
        r = gitx.gitr("tag", "-f", tag, br)
        out += f"; tag {tag}" if not r.returncode else f"; tag not set: {gitx.gerr(r)}"
    print(out + f". Do not develop {br} further: rework means a new module or a task from {into}")


def register(sp):
    q = sp.add_parser("deliver", help="deliver a module: squash into the target branch, journal -> decisions.md and summary.md")
    q.add_argument("module")
    q.add_argument("--into", metavar="BRANCH", help="target branch (default: the module base, the feature branch it was created from)")
    q.add_argument("-m", "--message", help="commit title (default: «<module>: <plan title>»)")
    q.add_argument("--in-place", action="store_true", help="journal already in the current branch: fold it into md and commit")
    q.add_argument("--rerender", action="store_true",
                   help="module already delivered: rebuild md from the journal in --from (default: archive tag), no commit")
    q.add_argument("--from", dest="from_", metavar="REF", help="for --rerender: tag or commit holding the module journal")
    q.add_argument("--area", help="for --rerender: area, if the journal's module.json has none")
    q.add_argument("--force", action="store_true", help="deliver with open tasks and questions")
    q.add_argument("--dry", action="store_true", help="only show what would happen")
    q.add_argument("--by")
    q.set_defaults(func=cmd_deliver)
