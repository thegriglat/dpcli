"""deliver — deliver a module: squash the module branch into the target branch; the journal stays in the module branch
(and under an archive tag); only human-readable md from <plan_dir>/<module>/ reaches the target: decisions and
questions, implementation summary.

  deliver <module> [--into BRANCH] [-m TEXT] [--force] [--dry]   squash the module branch into BRANCH's copy, commit, archive tag
  deliver <module> --in-place [--dry]                              journal already in the current branch: fold it into md
  deliver <module> --rerender [--from REF] [--area A]              rebuild md of a delivered module from the journal in REF (archive tag)

After delivery the module's plan and contracts get status: closed, INDEX.md is rebuilt (docs index).
"""
